// Lists every npm package that ends up inside dist/index.html, with its licence, and writes the
// third-party part of NOTICE from that list. `--check` fails when NOTICE is out of date.
import { build } from 'vite';
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const packages = new Map();
await build({
  root,
  logLevel: 'silent',
  build: { write: false },
  plugins: [
    {
      name: 'collect-packages',
      generateBundle(_, bundle) {
        for (const out of Object.values(bundle)) {
          if (out.type !== 'chunk') continue;
          for (const id of Object.keys(out.modules)) {
            const m = /node_modules\/((?:@[^/]+\/)?[^/]+)\//.exec(id.replace(/\\/g, '/'));
            if (m && !packages.has(m[1]))
              packages.set(
                m[1],
                id.slice(
                  0,
                  id.lastIndexOf(`node_modules/${m[1]}/`) + `node_modules/${m[1]}`.length,
                ),
              );
          }
        }
        // CSS assets (the Inter font) are not chunks: add what index.html imports by hand.
        packages.set(
          '@fontsource-variable/inter',
          path.join(root, 'node_modules/@fontsource-variable/inter'),
        );
      },
    },
  ],
});

const rows = [...packages.entries()]
  .map(([name, dir]) => {
    const pkg = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'));
    const author = typeof pkg.author === 'string' ? pkg.author : (pkg.author?.name ?? '');
    const licenceFile = fs
      .readdirSync(dir)
      .find((f) => /^(licen[cs]e|copying)(\.(md|txt))?$/i.test(f));
    const text = licenceFile ? fs.readFileSync(path.join(dir, licenceFile), 'utf8').trim() : '';
    return {
      name,
      version: pkg.version,
      license: pkg.license ?? 'see package',
      author: author.replace(/\s*<[^>]*>/, '').replace(/\s*\([^)]*\)/, ''),
      text,
    };
  })
  .sort((a, b) => a.name.localeCompare(b.name));

const table = rows
  .map((r) => `- ${r.name} ${r.version} — ${r.license}${r.author ? ` — ${r.author}` : ''}`)
  .join('\n');
const notice = `Vinyl Shelf
Copyright (c) 2026 Lucas Van De Weerd
Licensed under the MIT License (see LICENSE).

The built page (index.html) contains the following open-source packages, each under its own
licence; their licence texts follow at the end of this file. The list is generated by
scripts/notice.mjs from what the build actually bundles.

${table}

The Inter typeface (in @fontsource-variable/inter) is by Rasmus Andersson and is licensed under
the SIL Open Font License 1.1.

Ideas, credited, no code taken:
- The vinyl players this shelf hands albums to are the author's own projects (MIT).
- The cube shelf is modelled on the common 4 × 4 cube bookcase; no brand, model or drawing is used.

Cover art: albums without a cover get one drawn by the page; covers from your own music folder
stay on your computer and are never part of this repository.

LICENCE TEXTS
${rows.map((r) => `\n──── ${r.name} ${r.version} ────\n\n${r.text || `${r.license} (no licence file in the package)`}\n`).join('')}`;
const file = path.join(root, 'NOTICE');
if (process.argv.includes('--check')) {
  const now = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
  if (now !== notice) {
    console.error('NOTICE is out of date: run node scripts/notice.mjs');
    process.exit(1);
  }
  console.log(`NOTICE lists ${rows.length} bundled packages and is up to date`);
} else {
  fs.writeFileSync(file, notice);
  console.log(`NOTICE written: ${rows.length} packages`);
  console.log(table);
}
